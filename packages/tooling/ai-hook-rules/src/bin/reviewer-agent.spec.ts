import { describe, it, expect, vi } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';

import {
    REVIEWER_AGENT_MARKER, REVIEWER_AGENT_NAME, REVIEWER_AGENT_TEMPLATE, renderReviewerAgent, reviewerAgentPath,
    reviewerAgentStale, writeReviewerAgent,
} from './reviewer-agent';
import { REVIEWER_AGENT_SURFACE, managedSurfaceDrift, repairRegistrationAt } from './hook-registration';
import { renderShim, shimPath } from './shim';
import { shimStaleDenyReason } from './shim-deny-reason';
import { UPGRADE_SHIM_CMD } from './l0-allowlist';
import { runUpgradeShim } from './upgrade-shim';
import { specTempDirs } from '@webpieces/rules-config';

function mktmp(): string {
    return specTempDirs.makeReal('wp-reviewer-agent-');
}

// A webpieces-hooked tree: the committed shim exists (which is what makes the reviewer agent a managed file).
function hookedRepo(): string {
    const root = mktmp();
    fs.mkdirSync(path.dirname(shimPath(root)), { recursive: true });
    fs.writeFileSync(shimPath(root), renderShim(), { mode: 0o755 });
    return root;
}

/**
 * The generic PR-gate reviewer agent (issue #938): a checklist-agnostic Claude agent definition webpieces
 * owns, writes and polices exactly like the committed shim.
 */
describe('renderReviewerAgent — the generic reviewer definition', () => {
    const agent = renderReviewerAgent();

    it('is a Claude agent file named webpieces-reviewer with exactly the reviewer tools', () => {
        expect(agent.startsWith('---\nname: webpieces-reviewer\n')).toBe(true);
        expect(agent).toContain('\ntools: Read, Grep, Glob, Bash, Write\n---\n');
        expect(REVIEWER_AGENT_NAME).toBe('webpieces-reviewer');
        expect(REVIEWER_AGENT_MARKER).toBe('.claude/agents/webpieces-reviewer.md');
    });

    it('says it is generated and names the cure', () => {
        expect(agent).toContain('Generated by webpieces');
        expect(agent).toContain('do not edit; regenerate with pnpm wp-upgrade-shim');
    });

    it('is checklist-agnostic: one or more checklists, each over its own scope, one verdict each', () => {
        expect(agent).toContain('ONE OR MORE instructions files by absolute path, one per checklist');
        expect(agent).not.toContain('.webpieces/');
        expect(agent).toContain('ONLY against its own in-scope files');
        expect(agent).toContain('Exactly ONE verdict file per checklist you were handed');
        expect(agent).toContain('nothing for a checklist you were not handed');
    });

    it('never edits anything but its verdict files', () => {
        expect(agent).toContain('You NEVER edit code, config, docs, or any file other than those verdict files.');
    });

    it('carries no version stamp, so it only changes when its words do', () => {
        expect(agent).not.toMatch(/\d+\.\d+\.\d+/);
    });

    // The shipped template is what a human (or the cp fallback) reads; it must be the same bytes.
    it('ships byte-identical as templates/webpieces-reviewer.md', () => {
        const template = path.join(__dirname, '..', '..', 'templates', REVIEWER_AGENT_TEMPLATE);
        expect(fs.readFileSync(template, 'utf8')).toBe(agent);
    });
});

describe('writeReviewerAgent + reviewerAgentStale — a managed surface', () => {
    it('is not a surface at all in a tree webpieces never installed into', () => {
        expect(reviewerAgentStale(mktmp())).toBe(false);
        expect(reviewerAgentStale(null)).toBe(false);
    });

    it('is stale when MISSING from a hooked tree', () => {
        const root = hookedRepo();
        expect(reviewerAgentStale(root)).toBe(true);
        expect(managedSurfaceDrift(root)).toContain(REVIEWER_AGENT_SURFACE);
    });

    it('is stale when HAND-EDITED', () => {
        const root = hookedRepo();
        writeReviewerAgent(root);
        fs.appendFileSync(reviewerAgentPath(root), '\nAlso review style.\n');
        expect(reviewerAgentStale(root)).toBe(true);
    });

    it('writes it (creating .claude/agents), reports the change once, and is then current', () => {
        const root = hookedRepo();
        expect(writeReviewerAgent(root)).toBe(true);
        expect(fs.readFileSync(reviewerAgentPath(root), 'utf8')).toBe(renderReviewerAgent());
        expect(writeReviewerAgent(root)).toBe(false);
        expect(reviewerAgentStale(root)).toBe(false);
    });
});

describe('fault S names the reviewer agent and its cure', () => {
    it('prints the reviewer-agent note only when that surface drifted, with pnpm wp-upgrade-shim as Option 1', () => {
        const withAgent = shimStaleDenyReason('0.4.700', '/tmp/wp-root', [REVIEWER_AGENT_SURFACE], false);
        expect(withAgent).toContain(`  ${REVIEWER_AGENT_SURFACE}`);
        expect(withAgent).toContain('generic PR-gate reviewer agent webpieces owns');
        expect(withAgent).toContain(`run EXACTLY: 'cd /tmp/wp-root && ${UPGRADE_SHIM_CMD}'`);
        expect(withAgent).not.toContain('"');
        const without = shimStaleDenyReason('0.4.700', '/tmp/wp-root', ['.claude/webpieces/ai-hook.sh'], false);
        expect(without).not.toContain('generic PR-gate reviewer agent');
    });
});

describe('wp-upgrade-shim repairs a missing or hand-edited reviewer agent', () => {
    it('writes it, says so, and verifies clean', () => {
        const root = hookedRepo();
        repairRegistrationAt(root);
        const logged: string[] = [];
        const spy = vi.spyOn(console, 'log').mockImplementation((line: string): void => { logged.push(line); });
        const code = runUpgradeShim(root);
        spy.mockRestore();
        expect(code).toBe(0);
        expect(fs.readFileSync(reviewerAgentPath(root), 'utf8')).toBe(renderReviewerAgent());
        expect(logged.some((l: string): boolean => l.includes(REVIEWER_AGENT_MARKER))).toBe(true);
        expect(managedSurfaceDrift(root)).not.toContain(REVIEWER_AGENT_SURFACE);
    });
});
