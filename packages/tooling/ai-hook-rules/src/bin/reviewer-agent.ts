import * as fs from 'fs';
import * as path from 'path';

import { shimPath } from './shim';

// ---------------------------------------------------------------------------
// THE GENERIC REVIEWER AGENT — `.claude/agents/webpieces-reviewer.md`, a webpieces-owned, committed file
// (issue #938).
//
// Every PR-gate checklist used to name its OWN agent type, one `.claude/agents/<name>-reviewer.md` each.
// Those files added almost nothing over the checklist doc — a tool restriction and a paragraph saying
// "read your instructions file" — were annoying to author per checklist, and drifted (#863: Codex never
// read them at all). They also forced one subagent per checklist. So a repo now names ONE agent type in
// `commands.pr-gate` (`webpieces-reviewer` unless `overrideReviewerAgent` is true), and this is the one webpieces ships: checklist-agnostic, because
// everything checklist-specific is in the per-run instructions files `wp-review-upsert-pr` generates.
//
// It is a MANAGED SURFACE, exactly like `.claude/webpieces/ai-hook.sh`: GENERATED from
// renderReviewerAgent(), byte-STABLE across releases (no version stamp, so it changes only when its own
// words do), written by `wp-install-ai-hooks` and `wp-upgrade-shim`, and checked by managedSurfaceDrift()
// so a missing, stale or hand-edited copy is flagged with `pnpm wp-upgrade-shim` as the cure. A repo
// that wants different words sets `"overrideReviewerAgent": true` and `reviewerAgentName` to an agent of its
// own instead of editing this.
//
// fs + path + ./shim only, like the rest of this directory: the cure must run on a tree too broken to
// load the rule engine.
// ---------------------------------------------------------------------------

/** The agent type this file registers — the reviewer every repo gets unless it sets `overrideReviewerAgent`. */
export const REVIEWER_AGENT_NAME = 'webpieces-reviewer';

/** The committed file, repo-relative — also the name the drift check reports it under. */
export const REVIEWER_AGENT_MARKER = `.claude/agents/${REVIEWER_AGENT_NAME}.md`;

/** The copy that ships in the package, byte-identical to renderReviewerAgent() (locked by a unit test). */
export const REVIEWER_AGENT_TEMPLATE = `${REVIEWER_AGENT_NAME}.md`;

// webpieces-disable no-function-outside-class -- pure fs+path helper beside shimPath, in the dependency-free bin module
export function reviewerAgentPath(projectRoot: string): string {
    return path.join(projectRoot, ...REVIEWER_AGENT_MARKER.split('/'));
}

// webpieces-disable no-function-outside-class -- pure renderer beside renderShim, in the dependency-free bin module
export function renderReviewerAgent(): string {
    return `---
name: ${REVIEWER_AGENT_NAME}
description: Generic PR-gate reviewer. Reviews a diff against one or more checklist docs, each over its own in-scope files, and submits exactly one verdict per checklist through pnpm wp-write-review. Spawned by \`pnpm wp-review-upsert-pr\`, which names the instructions files to read. Never edits code.
tools: Read, Grep, Glob, Bash, Write
---

<!-- Generated by webpieces (@webpieces/ai-hook-rules) — do not edit; regenerate with pnpm wp-upgrade-shim.
     To change how reviews are done, set commands.pr-gate "overrideReviewerAgent": true and "reviewerAgentName" to an agent of your own. -->

You are a PR-gate reviewer. You did not write this change, and your job is to judge it against the
checklist(s) you are handed — nothing else.

## What you are given

Your caller names ONE OR MORE instructions files by absolute path, one per checklist
(\`<checklist-id>.instructions.md\`). Read every one of them FIRST. Each is regenerated on every run and
holds, for its checklist:

- the checklist doc to review against — the substance of that review;
- the files in scope, each with its extracted diff and the absolute path of the full source;
- the diff manifest, the diff basis, and any pre-resolved context for this repo;
- the exact verdict format, and the exact command that submits it.

Work only from those files. Nothing about any checklist is restated here, so nothing here can drift.

## Before you review: the round budget

For EACH checklist you were handed, run \`pnpm wp-write-review --checklist <id> --check\` first. It counts
how many times that checklist has already been reviewed on this branch against the repository's
\`maxReviewerRounds\`. When it REFUSES, do not review that checklist and submit nothing for it: report its
refusal verbatim to your caller ("I am not allowed to review <id>: …"). \`wp-write-review\` refuses an
over-budget verdict anyway, so a review past the budget is wasted work that cannot be recorded.

## How to review

1. Handle each checklist SEPARATELY. Read its doc, then its in-scope diffs, then the full source of every
   in-scope file — a hunk shows what changed, only the whole file shows what it changed into.
2. Judge each checklist ONLY against its own in-scope files. A finding that belongs to another checklist
   is not a finding for this one; a matched file that turns out to be irrelevant gets one sentence.
3. Read other files for context when a judgement needs it, but do not go hunting: no searches through
   \`node_modules\`, no re-deriving the dependency graph. If something you need is missing, say so in
   \`output\` and judge what you could see.

## What you submit

Exactly ONE verdict per checklist you were handed — and nothing for a checklist you were not handed —
in the format its instructions file gives, submitted through \`pnpm wp-write-review --checklist <id>\`
with the verdict JSON on stdin (a heredoc is simplest), or \`--file <path>\` naming a scratch file. It validates
it, writes the verdict file, and records that YOU wrote it. A verdict file written any other way —
by you, or by the coordinating agent on your behalf — is rejected by the gate, so there is no other route.

You NEVER edit code, config, docs, or any other file in the repo. You never write \`summary.json\` or an
\`override-<id>.json\`. If a finding needs a human's decision, say so in \`output\`; the coordinating
agent is the one with the human.
`;
}

/**
 * True when this tree is webpieces-hooked (its committed shim exists) and the reviewer agent is MISSING or
 * differs from renderReviewerAgent(). Gated on the shim for the same reason `committedShimStale` is gated
 * on its own file: a tree webpieces never installed into has no managed surface to police.
 */
// webpieces-disable no-function-outside-class -- pure fs+path helper beside committedShimStale, in the dependency-free bin module
export function reviewerAgentStale(root: string | null): boolean {
    if (root === null || !fs.existsSync(shimPath(root))) return false;
    const target = reviewerAgentPath(root);
    if (!fs.existsSync(target)) return true;
    return fs.readFileSync(target, 'utf8') !== renderReviewerAgent();
}

/**
 * Write the reviewer agent under `root`, returning true when the file changed. Creates `.claude/agents/`
 * when it is absent — that directory is what a Claude Code session scans for agent types.
 */
// webpieces-disable no-function-outside-class -- pure fs+path writer beside writeShim, in the dependency-free bin module
export function writeReviewerAgent(root: string): boolean {
    const target = reviewerAgentPath(root);
    const desired = renderReviewerAgent();
    if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === desired) return false;
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, desired);
    return true;
}
