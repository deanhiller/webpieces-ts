import * as path from 'path';
import { ContextKeyRef, ImportConfig } from '../config/ImportConfig';
import { SpecOperation, SpecParameter } from '../spec/VendorSpec';
import { VendorSpec } from '../spec/VendorSpec';
import { JsDoc } from './JsDoc';
import { Names } from './Names';
import { TypeEmitter } from './TypeEmitter';

/** `@Endpoint`'s side-effect contract, derived from the verb. */
const OPERATION_OF_VERB: Readonly<Record<string, string>> = {
    GET: 'READ',
    PUT: 'WRITE_IDEMPOTENT',
    DELETE: 'WRITE_IDEMPOTENT',
    POST: 'WRITE',
    PATCH: 'WRITE',
};

/** The framework module every generated contract imports its decorators from. */
const CORE_UTIL = '@webpieces/core-util';

/** The contract's `@summary` limit (`SummaryGuard`). */
const SUMMARY_MAX = 100;

/** One generated method: its source text and the core-util symbols it uses. */
class EmittedMethod {
    constructor(
        readonly text: string,
        readonly symbols: readonly string[],
    ) {}
}

/**
 * The whole generated file: banner, imports, every reached DTO class and string enum, then the
 * `EXTERNAL_OUTBOUND` contract. Deterministic — operations in the import file's order, declarations
 * sorted — so regenerating from the same inputs is byte-identical.
 */
export class ContractEmitter {
    private readonly names = new Names();
    private readonly doc = new JsDoc();

    emit(config: ImportConfig, spec: VendorSpec): string {
        const types = new TypeEmitter(spec);
        const symbols = new Set<string>(['ApiPath', 'AuthorizationType', 'Endpoint', 'EXTERNAL_OUTBOUND', 'WpAuth', 'WpAuthorization', 'vendorAuth']);
        const keyImports = new Map<string, Set<string>>();
        const methods = config.operations.map((operationId: string) => {
            const method = this.method(spec.operation(operationId), config, types);
            for (const symbol of method.symbols) symbols.add(symbol);
            return method.text;
        });
        const classKeys = this.contextKeys(config.classContextKeys, keyImports, symbols);
        for (const keys of config.methodContextKeys.values()) this.contextKeys(keys, keyImports, symbols);
        // A key owned by core-util itself (WebpiecesCoreHeaders.REQUEST_ID) joins the one core-util import.
        for (const name of keyImports.get(CORE_UTIL) ?? []) symbols.add(name);
        keyImports.delete(CORE_UTIL);
        const parts = [
            this.banner(config),
            this.imports(symbols, keyImports),
            // The DTOs come FIRST: `emitDecoratorMetadata` names each parameter's class while the
            // contract is being decorated, so a DTO declared below it is still in its TDZ.
            ...types.rendered().map((declaration: string) => `${declaration}\n`),
            this.classDoc(spec),
            `@ApiPath('')\n${classKeys === '' ? '' : `@ExternalContextKeys(${classKeys})\n`}export abstract class ${config.contract} {\n${methods.join('\n')}}\n`,
        ];
        return parts.join('');
    }

    private banner(config: ImportConfig): string {
        return [
            '// GENERATED by wp-openapi-import — DO NOT EDIT. Every byte is regenerated from the vendor spec.',
            `// spec:   ${config.specAsWritten}`,
            `// import: ${path.basename(config.configPath)}`,
            '',
            '',
        ].join('\n');
    }

    private imports(symbols: ReadonlySet<string>, keyImports: ReadonlyMap<string, ReadonlySet<string>>): string {
        const lines = [`import {\n${[...symbols].sort().map((symbol: string) => `    ${symbol},\n`).join('')}} from '${CORE_UTIL}';`];
        for (const from of [...keyImports.keys()].sort()) {
            lines.push(`import { ${[...keyImports.get(from)!].sort().join(', ')} } from ${this.names.literal(from)};`);
        }
        return `${lines.join('\n')}\n\n`;
    }

    private classDoc(spec: VendorSpec): string {
        const info = spec.root.at('info');
        const lines = this.doc.prose(info.text('description'));
        const title = info.text('title');
        const head = title === undefined ? [] : [this.doc.oneLine(title, 200), ...(lines.length > 0 ? [''] : [])];
        const all = [...head, ...lines];
        return this.doc.block(all.length > 0 ? all : ['A vendor API this service calls (EXTERNAL_OUTBOUND).'], '');
    }

    /** `Owner.KEY, ...` for `@ExternalContextKeys`, recording each import it needs. */
    private contextKeys(keys: readonly ContextKeyRef[], keyImports: Map<string, Set<string>>, symbols: Set<string>): string {
        if (keys.length === 0) return '';
        symbols.add('ExternalContextKeys');
        for (const key of keys) {
            const names = keyImports.get(key.from) ?? new Set<string>();
            names.add(key.importedName());
            keyImports.set(key.from, names);
        }
        return keys.map((key: ContextKeyRef) => key.symbol).join(', ');
    }

    private method(operation: SpecOperation, config: ImportConfig, types: TypeEmitter): EmittedMethod {
        const symbols = new Set<string>([operation.verb, OPERATION_OF_VERB[operation.verb]]);
        const methodName = this.names.methodName(operation.operationId);
        const pascal = this.names.pascal(methodName);
        const parameters = this.parameters(operation, pascal, types, symbols);
        const returnType = operation.responseBody === undefined ? 'void' : types.typeOf(operation.responseBody, `${pascal}Response`);
        const options = returnType === 'void' ? ', { responseBody: NONE }' : '';
        if (returnType === 'void') symbols.add('NONE');
        const methodKeys = config.methodContextKeys.get(operation.operationId) ?? [];
        const lines = [
            this.methodDoc(operation, returnType),
            `    @WpAuth([vendorAuth(${this.names.literal(config.vendorAuth)})])\n`,
            '    @WpAuthorization({ authType: AuthorizationType.SERVICE_ONLY })\n',
            `    @Endpoint(${operation.verb}, ${this.names.literal(operation.path)}, ${OPERATION_OF_VERB[operation.verb]}, EXTERNAL_OUTBOUND${options})\n`,
            methodKeys.length === 0 ? '' : `    @ExternalContextKeys(${methodKeys.map((key: ContextKeyRef) => key.symbol).join(', ')})\n`,
            '    // webpieces-disable no-unmanaged-exceptions -- generated contract stub, never executed\n',
            `    ${methodName}(${parameters}): Promise<${returnType}> {\n`,
            "        throw new Error('contract only');\n",
            '    }\n',
        ];
        return new EmittedMethod(lines.join(''), [...symbols]);
    }

    /** Path params in placeholder order, then the body, then the (optional) query string. */
    private parameters(operation: SpecOperation, pascal: string, types: TypeEmitter, symbols: Set<string>): string {
        const used = new Set<string>();
        const unique = (name: string): string => {
            let candidate = name;
            for (let n = 2; used.has(candidate); n++) candidate = `${name}${n}`;
            used.add(candidate);
            return candidate;
        };
        const parameters = operation.pathParameters.map((parameter: SpecParameter) => {
            symbols.add('PathParam');
            const type = types.typeOf(parameter.schema, this.names.dtoName(`${pascal}${this.names.pascal(parameter.name)}`));
            return `@PathParam(${this.names.literal(parameter.name)}) ${unique(this.names.camel(parameter.name) || 'param')}: ${type}`;
        });
        if (operation.requestBody !== undefined) {
            parameters.push(`${unique('request')}: ${types.typeOf(operation.requestBody, `${pascal}Request`)}`);
        }
        if (operation.queryParameters.length > 0) {
            symbols.add('QueryString');
            symbols.add('QueryParams');
            const required = operation.queryParameters.some((parameter: SpecParameter) => parameter.required);
            parameters.push(`@QueryString() ${unique('query')}${required ? '' : '?'}: QueryParams`);
        }
        return parameters.join(', ');
    }

    private methodDoc(operation: SpecOperation, returnType: string): string {
        const prose = this.doc.prose(operation.description ?? operation.summary);
        const lines = prose.length > 0 ? [...prose] : [`Calls ${operation.verb} ${this.doc.escape(operation.path)}.`];
        if (operation.queryParameters.length > 0) {
            lines.push('', 'Query parameters the vendor documents (pass them in `query`):');
            for (const parameter of operation.queryParameters) {
                const type = this.queryType(parameter);
                const description = this.doc.oneLine(parameter.description ?? '', 200);
                const tail = description === '' ? '' : `: ${description}`;
                lines.push(`- \`${this.doc.escape(parameter.name)}\` (${type}${parameter.required ? ', required' : ''})${tail}`);
            }
        }
        const summarySource = operation.summary ?? operation.description?.split('\n')[0] ?? operation.operationId;
        lines.push('', `@summary ${this.doc.oneLine(summarySource, SUMMARY_MAX)}`);
        if (returnType !== 'void') {
            lines.push(`@returns ${this.doc.oneLine(operation.responseDescription ?? 'The vendor response.', 200) || 'The vendor response.'}`);
        }
        return this.doc.block(lines, '    ');
    }

    /** A documented query parameter's type, as prose — the multimap itself is untyped. */
    private queryType(parameter: SpecParameter): string {
        const type = parameter.schema.text('type');
        if (type === 'array') return `${parameter.schema.at('items').text('type') ?? 'string'}, repeatable`;
        const ref = parameter.schema.text('$ref');
        if (ref !== undefined) return this.doc.escape(ref.slice(ref.lastIndexOf('/') + 1));
        return type ?? 'string';
    }
}
